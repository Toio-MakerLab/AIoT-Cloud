export const viToAscii = (str: string) => {
  if (typeof str !== 'string') return '';
  for (const [key, value] of Object.entries(VI_MAP)) {
    str = str.replace(new RegExp(key, 'g'), value);
  }
  return str;
};
export const slugify = (str: string) => {
  if (typeof str !== 'string') return '';
  str = viToAscii(str);
  str = str.toLowerCase();
  str = str.replace(/[^a-z0-9]+/g, '-');
  str = str.replace(/^-+|-+$/g, '');
  return str;
};
